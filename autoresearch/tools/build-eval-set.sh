#!/usr/bin/env bash
# Auto-generates eval-set entries from .tlk/archive/<feature>/.
# Each archived feature with both spec.md and handoff-log.md becomes an
# eval-set/<feature-id>.md file containing a list of (requirement, expected)
# pairs. Existing files are NOT modified (per program.md invariants).
#
# Override the artefacts directory with $ARTEFACTS_DIR.
#
# Usage:  talaka/autoresearch/tools/build-eval-set.sh
# Run from project root.

set -euo pipefail

# Enable verbose tracing if VERBOSE=1 or DEBUG=1
if [ "${VERBOSE:-}" = "1" ] || [ "${DEBUG:-}" = "1" ]; then
  export PS4='+ $(date -u "+%Y-%m-%dT%H:%M:%SZ")\040 '
  set -x
fi

PKG_DIR="$(cd "$(dirname "$0")/.." && pwd)"
PROJECT_ROOT="$(pwd)"
ARTEFACTS="${ARTEFACTS_DIR:-$PROJECT_ROOT/.tlk}"

EVAL_DIR="$ARTEFACTS/autoresearch/eval-set"
ARCHIVE_DIR="$ARTEFACTS/archive"

mkdir -p "$EVAL_DIR"

if [ ! -d "$ARCHIVE_DIR" ]; then
  echo "No $ARCHIVE_DIR yet — archive a feature first."
  exit 0
fi

added=0
skipped=0

for dir in "$ARCHIVE_DIR"/*/; do
  [ -d "$dir" ] || continue
  feature_id=$(basename "$dir")
  spec="${dir}spec.md"
  handoff="${dir}handoff-log.md"
  out="$EVAL_DIR/${feature_id}.md"

  if [ ! -f "$spec" ]; then
    skipped=$((skipped+1))
    continue
  fi
  # Skip features without a handoff-log — they produce empty reference outputs
  # that always score 0 and corrupt the baseline.
  if [ ! -f "$handoff" ]; then
    skipped=$((skipped+1))
    continue
  fi
  if [ -f "$out" ]; then
    skipped=$((skipped+1))
    continue
  fi

  # Extract acceptance criteria block.
  # Stops only at a top-level (##) heading, so ### sub-sections under ACs are included.
  criteria=$(awk '
    BEGIN{cap=0}
    /^##[[:space:]]+[Aa]cceptance/ {cap=1; next}
    cap==1 && /^##[[:space:]]/ {cap=0}
    cap==1 {print}
  ' "$spec")

  # Strip leading/trailing blank lines. Leading: sed. Trailing: $(...) already
  # drops trailing newlines, so only whitespace-only lines remain — trim those
  # with parameter expansion (BSD sed rejects the usual `{$d;N;ba}` idiom).
  criteria=$(printf '%s\n' "$criteria" | sed '/[^[:space:]]/,$!d')
  while [[ "$criteria" =~ $'\n'[[:space:]]*$ ]]; do
    criteria="${criteria%$'\n'*}"
  done

  if [ -z "$criteria" ]; then
    # Fallback: any heading containing "Acceptance" at any level
    criteria=$(awk '
      BEGIN{cap=0}
      /^#+[[:space:]]*[Aa]cceptance/ {cap=1; next}
      cap==1 && /^#[[:space:]]/ {cap=0}
      cap==1 {print}
    ' "$spec" | sed '/./,$!d')
  fi

  if [ -z "$criteria" ]; then
    criteria="(no Acceptance Criteria section found — see full spec)"
  fi

  # Extract the Bagnik → Zlydni code QA pass entry from handoff-log.
  # This section contains per-AC verification with file:line evidence,
  # test results, security/PII checks — exactly what the judge needs.
  built=""
  if [ -f "$handoff" ]; then
    built=$(awk '
      /Bagnik[^→]*→[^[]*\[code QA/ { cap=1; print; next }
      cap==1 && /^## / { cap=0 }
      cap==1 { print }
    ' "$handoff")
  fi

  # Fallback: look for any "PASS" Bagnik entry
  if [ -z "$built" ] && [ -f "$handoff" ]; then
    built=$(awk '
      /Bagnik.*PASS/ { cap=1; print; next }
      cap==1 && /^## / { cap=0 }
      cap==1 { print }
    ' "$handoff" | head -n 40)
  fi

  # Last resort: grab "What was built" lines
  if [ -z "$built" ] && [ -f "$handoff" ]; then
    built=$(grep -E -i 'what was built|implemented:|AC[0-9]' "$handoff" | head -n 10 || true)
  fi

  # Skip if we couldn't extract a meaningful reference output — it will always
  # score 0 and corrupt the baseline signal.
  if [ -z "$built" ]; then
    skipped=$((skipped+1))
    continue
  fi

  {
    echo "# Eval entry — $feature_id"
    echo ""
    echo "_Generated by build-eval-set.sh on $(date '+%Y-%m-%d'). Feature: \`$feature_id\`._"
    echo ""
    echo "## Requirements"
    echo ""
    printf '%s\n' "$criteria"
    echo ""
    echo "## Reference output"
    echo ""
    printf '%s\n' "$built"
  } > "$out"

  added=$((added+1))
done

echo "Eval-set: $added added, $skipped skipped."
echo "Files in: $EVAL_DIR"
